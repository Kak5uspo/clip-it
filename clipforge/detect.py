"""Chat-based highlight detection.

A highlight is a moment at which many viewers *react* within a few seconds:
with listed emotes, spelled-out laughter, question-mark spam or hype words.
Ordinary text does not count, because the biggest waves of plain messages are
prompted by the streamer (polls answered with "1" or "2", roll calls,
guessing games).

The burst-versus-baseline test (per-user cap, adaptive multiplier, minimum
rate, debounce) is ported from clippy's src/firehose.ts (MIT, Copyright (c)
2025 clippy contributors; see THIRD_PARTY_LICENSES.md). Counting reactions
only, the robust z-score, the minimum number of chatters, labels and the
stream-start fallback are clipforge's own.
"""
from __future__ import annotations

import json
import math
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from statistics import fmean, median

# Subscriptions and gifts appear in the log as comments with a text generated by Twitch.
_NOTICE = re.compile(
    r"\S+ (subscribed (at|with) |gifted a |is gifting |is continuing the Gift Sub|is paying forward the Gift)"
)
# Laughter and disbelief that viewers type out instead of using an emote.
_LAUGH = re.compile(r"a?ha(ha)+h?|he(he)+|hi(hi)+|xd+|lo+l|lmf?ao+|rofl|kek+w?", re.IGNORECASE)
_SHOCK = re.compile(r"[?!]*\?\?[?!]*")

# A label needs this share of the reactions in a burst, so that a single
# stray emote does not name the clip.
_LABEL_MIN_SHARE = 0.2

# Lower bound for the spread of square-rooted counts. Poisson noise gives 0.5;
# the margin covers the noisy estimate from a short, overlapping history.
# Simulated on 120 h of random chat at 0.3 to 20 messages/s: no false alarm.
_SPREAD_FLOOR = 0.7


@dataclass(frozen=True)
class Message:
    t: float  # seconds since the start of the VOD
    user: str
    text: str


@dataclass(frozen=True)
class Chapter:
    start: float
    end: float
    game: str


@dataclass(frozen=True)
class Chat:
    duration: float
    messages: list[Message]
    chapters: list[Chapter]
    streamer: str = ""
    title: str = ""


@dataclass(frozen=True)
class Highlight:
    spike_s: int  # second at which the chat starts to react
    start_s: float  # rough clip window, refined later by the fine cut
    end_s: float
    score: float  # robust z-score of the burst at its peak (square-root scale)
    rate: float  # reactions per second at the peak
    baseline: float  # the same for the preceding history
    chatters: int  # distinct viewers reacting at the peak
    label: str | None
    game: str | None


def read_chat(path: str | Path) -> Chat:
    """Read a chat log written by `TwitchDownloaderCLI chatdownload` (JSON)."""
    # ponytail: loads the whole file into memory (a 7 h stream of a large channel is ~20 MB);
    # switch to a streaming JSON parser if logs outgrow RAM.
    data = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    video = data.get("video") or {}
    streamer = data.get("streamer") or {}
    messages = []
    for comment in data.get("comments") or []:
        message = comment.get("message") or {}
        text = message.get("body") or ""
        if _NOTICE.match(text):
            continue
        commenter = comment.get("commenter") or {}
        messages.append(
            Message(
                t=float(comment.get("content_offset_seconds") or 0),
                user=str(commenter.get("_id") or commenter.get("name") or ""),
                text=text,
            )
        )
    messages.sort(key=lambda m: m.t)
    chapters = [
        Chapter(
            start=(c.get("startMilliseconds") or 0) / 1000,
            end=((c.get("startMilliseconds") or 0) + (c.get("lengthMilliseconds") or 0)) / 1000,
            game=c.get("gameDisplayName") or c.get("description") or "",
        )
        for c in video.get("chapters") or []
    ]
    duration = video.get("end") or video.get("length") or (messages[-1].t if messages else 0)
    return Chat(
        duration=float(duration),
        messages=messages,
        chapters=chapters,
        streamer=str(streamer.get("login") or streamer.get("name") or ""),
        title=str(video.get("title") or ""),
    )


def _reaction(m: Message, emotes: dict[str, set[str]], words: set[str]) -> str | None:
    """Label of a reaction, "" for a hype word without one, None for ordinary chat.

    Emotes count only when they are listed: a channel's other emotes are mostly
    greetings and dancing, which come in waves but are not highlights.
    """
    for token in m.text.split():
        for label, names in emotes.items():
            if token in names:
                return label
        bare = token.rstrip(".,!?").lower()
        if _LAUGH.fullmatch(bare):
            return "laugh"
        if _SHOCK.fullmatch(token):
            return "shock"
        if bare in words:
            return ""
    return None


def detect(chat: Chat, s: dict) -> list[Highlight]:
    """Return all highlights of a stream, strongest first.

    `s` are the settings from `config.detect_settings`.

    The robust z-score, (burst - median) / (1.4826 x MAD), is taken on the
    square-root scale. Counts scatter like Poisson noise, whose spread grows
    with the level; the square root makes the spread the same at every level.
    On raw counts a threshold of 4 lets dozens of random waves per 10 hours
    through in a quiet chat. The median comes from the recent history, the MAD
    from the whole stream: 120 seconds are too few to estimate a spread, and a
    jumpy spread makes the ranking erratic.
    """
    window, history, cap = s["burst_window_s"], s["baseline_window_s"], s["max_msgs_per_user"]

    seconds = int(chat.duration) + 1
    reactions: list[list[tuple[str, str]]] = [[] for _ in range(seconds)]  # per second: (user, label)
    for m in chat.messages:
        label = _reaction(m, s["emotes"], s["words"])
        if label is not None and 0 <= m.t < seconds:
            reactions[int(m.t)].append((m.user, label))

    # Burst per second: reactions of the last `window` seconds, at most `cap` per user.
    bursts, chatters = [], []
    for sec in range(seconds):
        per_user = Counter(user for bucket in reactions[max(0, sec - window + 1) : sec + 1] for user, _ in bucket)
        bursts.append(sum(min(count, cap) for count in per_user.values()))
        chatters.append(len(per_user))

    roots = [math.sqrt(b) for b in bursts]
    stream_mean, stream_level = fmean(bursts), median(roots)
    spread = max(1.4826 * median(abs(r - stream_level) for r in roots), _SPREAD_FLOOR)
    allowed = {g.lower() for g in s["games"]}

    def game_at(sec: int) -> str | None:
        return next((c.game for c in chat.chapters if c.start <= sec < c.end), None)

    spikes: dict[int, tuple[float, float]] = {}  # second -> (z-score, baseline rate)
    for sec in range(seconds):
        rate = bursts[sec] / window
        if chatters[sec] < s["min_chatters"] or rate <= s["min_rate"]:
            continue
        if allowed and chat.chapters and (game_at(sec) or "").lower() not in allowed:
            continue
        # History = the bursts that ended before the current window began. A stream
        # too young to have one is measured against its own overall level.
        lo, hi = sec - window - history + 1, sec - window + 1
        mean, level = (fmean(bursts[lo:hi]), median(roots[lo:hi])) if lo >= 0 else (stream_mean, stream_level)
        baseline = mean / window
        multiplier = s["multiplier"]
        if multiplier == "auto":
            multiplier = max(1.5, 2.5 - 0.1 * baseline)
        z = (roots[sec] - level) / spread
        if rate > baseline * multiplier and z >= s["min_z"]:
            spikes[sec] = (z, baseline)

    # Keep the peaks: strongest first, nothing within `debounce_s` of a stronger one.
    peaks: list[int] = []
    for sec in sorted(spikes, key=lambda sec: spikes[sec][0], reverse=True):
        if all(abs(sec - other) >= s["debounce_s"] for other in peaks):
            peaks.append(sec)

    highlights = []
    for peak in peaks:
        score, baseline = spikes[peak]
        if s["min_score"] is not None and score < s["min_score"]:
            continue
        onset = peak
        while onset - 1 in spikes:
            onset -= 1
        spike_s = max(0, onset - window + 1)
        labels = Counter(label for bucket in reactions[max(0, peak - window + 1) : peak + 1] for _, label in bucket)
        total = sum(labels.values())
        label, hits = max(((k, v) for k, v in labels.items() if k), key=lambda kv: kv[1], default=(None, 0))
        highlights.append(
            Highlight(
                spike_s=spike_s,
                start_s=max(0.0, spike_s - s["pre_roll_s"]),
                end_s=min(chat.duration, spike_s + s["post_roll_s"]),
                score=round(score, 2),
                rate=round(bursts[peak] / window, 2),
                baseline=round(baseline, 2),
                chatters=chatters[peak],
                label=label if hits >= _LABEL_MIN_SHARE * total else None,
                game=game_at(peak),
            )
        )
    return highlights
